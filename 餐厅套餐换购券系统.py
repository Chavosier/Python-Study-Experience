def delete(pos, amount):
    """
    从coupon数组中查找可用的换购券
    pos: 开始查找的位置
    amount: 惠品订单金额
    返回: 折扣金额（若找到可用券则返回券金额，否则返回0）
    """
    discount = 0
    i = pos
    while i < len(coupon): #只能用于不高于换购券金额的惠品
        if amount <= coupon[i][0]: # 优先使用获得时间最早的
            discount = amount  # 实际抵扣金额为惠品金额
            coupon.pop(i)      # 将数组coupon中下标为i的元素删除
            break
        i += 1
    return discount

