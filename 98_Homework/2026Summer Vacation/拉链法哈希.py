"""
G. 拉链法
题目描述：
哈希表又称散列表，是指任意的键值 key 都唯一对应到哈希表中的某个位置。
给定哈希函数：
    def hashing(key): return key % M
其中 M 是一个固定的常数。
可能多个键值对应哈希表的同一个位置，于是就有了拉链法。
拉链法是在每个存放数据的地方开一个链表，如果有多个键值索引到同一个地方，
就把他们都放到那个位置的链表里。
查询的时候需要把对应位置的链表整个扫一遍，对其中的每个数据比较其键值与查询的键值是否一致。

现在你要进行下面 3 种操作：
(1) 往哈希表加入一个键值为 k，数值为 v 的元素。如果哈希表的该位置已有元素，则加入该位置链表的开头；
(2) 查询某个键值为 k 的元素对应的数值 v；
(3) 查询某个键值为 k 的元素在链表中的位置。

输入格式：
第一行两个正整数 n, M，分别表示操作次数和模数。
接下来 n 行每行包括 2 或 3 个整数，表示一个操作。
操作可以是以下四种之一：
    1 k v  表示第一种操作（插入）
    2 k    表示第二种操作（查询值）
    3 k    表示第三种操作（查询位置）

输出格式：
输出包括若干行整数，为所有操作 2 和操作 3 的结果。

样例输入：
8 10
1 15 1
1 27 2
1 9 3
1 19 4
2 15
1 29 5
2 19
3 9

样例输出：
1
4
3

数据范围：
1 ≤ n ≤ 10⁴, 1 ≤ M ≤ 10⁵, 1 ≤ k ≤ 10⁹
保证键值互不相同。
"""

n, M = map(int, input().split())
dic = {}

for _ in range(n):
    t = list(map(int, input().split()))
    if t[0] == 1:
        # 插入操作：键值对 [k, v] 放到链表开头
        idx = t[1] % M
        if idx not in dic:
            dic[idx] = [[t[1], t[2]]]
        else:
            dic[idx].append([t[1], t[2]])
    elif t[0] == 2:
        # 查询键 k 对应的值 v
        idx = t[1] % M
        tmp = dic[idx]
        for item in tmp:
            if item[0] == t[1]:
                print(item[1])
                break
    else:
        # 查询键 k 在链表中的位置（从末尾往前数，即最早插入的位置）
        idx = t[1] % M
        tmp = dic[idx]
        for i in range(len(tmp)):
            if tmp[i][0] == t[1]:
                print(len(tmp) - i)
                break